import {CogIcon} from '@sanity/icons/Cog'
import {defineArrayMember, defineField, defineType} from 'sanity'
import {serviceOptions} from './options'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Website settings',
  type: 'document',
  icon: CogIcon,
  groups: [
    {name: 'photos', title: 'Photos', default: true},
    {name: 'contact', title: 'Contact'},
    {name: 'lease', title: 'Lease rules'},
    {name: 'payment', title: 'Payment'},
  ],
  fields: [
    defineField({
      name: 'heroImage',
      title: 'Main home page photo',
      description: 'A wide photo of the building or best room. Landscape, at least 2000 px wide.',
      type: 'photo',
      group: 'photos',
    }),
    defineField({
      name: 'aboutImage',
      title: '"Our family" photo',
      type: 'photo',
      group: 'photos',
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      description: 'Optional. Without a logo the name "L2 Angkor" is shown in text.',
      type: 'image',
      group: 'photos',
    }),
    defineField({
      name: 'gallery',
      title: 'Building & common area photos',
      description: 'Shown in the gallery on the home page. Drag to reorder.',
      type: 'array',
      group: 'photos',
      of: [defineArrayMember({type: 'galleryPhoto'})],
      options: {layout: 'grid'},
    }),

    defineField({name: 'phone', title: 'Phone number', type: 'string', group: 'contact'}),
    defineField({
      name: 'telegram',
      title: 'Telegram username',
      description: 'Without @',
      type: 'string',
      group: 'contact',
    }),
    defineField({
      name: 'whatsapp',
      title: 'WhatsApp number',
      description: 'With country code, digits only, e.g. 85512345678',
      type: 'string',
      group: 'contact',
      validation: (rule) => rule.regex(/^\d{8,15}$/).error('Digits only, with country code'),
    }),
    defineField({name: 'facebook', title: 'Facebook page link', type: 'url', group: 'contact'}),
    defineField({name: 'wechatId', title: 'WeChat ID', type: 'string', group: 'contact'}),
    defineField({name: 'wechatQr', title: 'WeChat QR code', type: 'image', group: 'contact'}),
    defineField({
      name: 'email',
      title: 'Public email',
      type: 'string',
      group: 'contact',
      validation: (rule) => rule.email(),
    }),
    defineField({name: 'address', title: 'Address', type: 'internationalizedArrayString', group: 'contact'}),
    defineField({
      name: 'mapEmbedUrl',
      title: 'Google Maps embed link',
      description: 'Google Maps → Share → Embed a map → copy only the link inside src="…"',
      type: 'url',
      group: 'contact',
    }),
    defineField({
      name: 'mapLink',
      title: 'Google Maps link',
      description: 'Google Maps → Share → Copy link',
      type: 'url',
      group: 'contact',
    }),

    defineField({
      name: 'minLeaseMonths',
      title: 'Minimum lease (months)',
      type: 'number',
      group: 'lease',
      initialValue: 3,
      validation: (rule) => rule.required().min(1).integer(),
    }),
    defineField({
      name: 'depositMonths',
      title: 'Deposit (months of rent)',
      type: 'number',
      group: 'lease',
      initialValue: 1,
      validation: (rule) => rule.required().min(0),
    }),
    defineField({
      name: 'petsAllowed',
      title: 'Pets',
      type: 'string',
      group: 'lease',
      initialValue: 'no',
      options: {
        list: [
          {title: 'No pets', value: 'no'},
          {title: 'Pets allowed', value: 'yes'},
        ],
        layout: 'radio',
      },
    }),
    defineField({
      name: 'electricityRate',
      title: 'Electricity price',
      description: 'Optional, e.g. "$0.25 per kWh"',
      type: 'string',
      group: 'lease',
    }),
    defineField({
      name: 'waterRate',
      title: 'Water price',
      description: 'Optional, e.g. "$1 per m³"',
      type: 'string',
      group: 'lease',
    }),
    defineField({
      name: 'sharedServices',
      title: 'Services for all tenants',
      description: 'Shown on the home page.',
      type: 'array',
      group: 'lease',
      of: [defineArrayMember({type: 'string'})],
      options: {list: serviceOptions, layout: 'grid'},
    }),

    defineField({
      name: 'paymentEnabled',
      title: 'Show payment section on the website',
      type: 'boolean',
      group: 'payment',
      initialValue: false,
    }),
    defineField({name: 'paymentQr', title: 'Payment QR code (KHQR)', type: 'image', group: 'payment'}),
    defineField({name: 'bankName', title: 'Bank', type: 'string', group: 'payment'}),
    defineField({name: 'accountName', title: 'Account name', type: 'string', group: 'payment'}),
    defineField({name: 'accountNumber', title: 'Account number', type: 'string', group: 'payment'}),
  ],
  preview: {prepare: () => ({title: 'Website settings'})},
})
